import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { bakeCube, bakeDfg, bakeDiffuse, cubeSize, lutSize, mipLevels, minimumRoughness, minimumNoV, prefilterSamples, dfgSamples, presets, radiance } from './imported-environment-bake.mjs';

if (process.argv.slice(2).some(value => value !== '--check')) throw new Error('Only --check is supported.');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const baker = await readFile(new URL('./imported-environment-bake.mjs', import.meta.url));
const environments = Object.fromEntries(presets.map(preset => {
  const source = direction => radiance(preset, direction), bytes = bakeCube(source);
  return [preset, { sha256: sha256(bytes), bytes: bytes.length, sh: bakeDiffuse(source), data: bytes.toString('base64') }];
}));
const dfg = bakeDfg();
const metadata = { format: 'strata-generated-environment', version: 1, source: 'analytic studio lobes / sky radiance; no external images',
  bakerSha256: sha256(baker), cubeSize, lutSize, mipLevels, minimumRoughness, minimumNoV, prefilterSamples, dfgSamples,
  dfgGrid: 'endpoint grid: NoV=0.0001+0.9999*(x/63)^2, roughness=0.06+0.94*y/63',
  convention: 'WebGPU cube +X,-X,+Y,-Y,+Z,-Z; linear RGB; irradiance SH; GGX alpha=roughness^2; single-scatter correlated Smith/Schlick DFG',
  references: ['https://google.github.io/filament/main/filament.html#lighting/imagebasedlights',
    'https://pbr-book.org/4ed/Reflection_Models/Roughness_Using_Microfacet_Theory', 'packages/core/src/rendering/raster-shaders.ts:evaluateDirectLight'],
  dfg: { sha256: sha256(dfg), bytes: dfg.length }, environments: Object.fromEntries(Object.entries(environments).map(([key, { data: _data, ...value }]) => [key, value])) };
const code = `// Generated by node scripts/generate-imported-environment.mjs. Only procedural data; do not edit.\n`
  + `export const environmentMetadata = ${JSON.stringify(metadata, null, 2)};\n`
  + `export const environmentCubeData: Record<'studio' | 'sky', string> = ${JSON.stringify(Object.fromEntries(Object.entries(environments).map(([key, value]) => [key, value.data])))};\n`
  + `export const environmentDfgData: string = ${JSON.stringify(dfg.toString('base64'))};\n`;
const output = new URL('../packages/core/src/imported/imported-environment-data.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== code) throw new Error('Generated environment data differs; run node scripts/generate-imported-environment.mjs.');
} else await writeFile(output, code);
console.log(JSON.stringify({ checked: process.argv.includes('--check'), bakerSha256: metadata.bakerSha256,
  cubeBytes: environments.studio.bytes + environments.sky.bytes, dfgBytes: dfg.length }));
